"""Generate whole map dots from the projected Natural Earth land outline."""

from bisect import bisect_right
from math import atan2, ceil, pi, sqrt
from pathlib import Path
import json
import re
from xml.etree import ElementTree


WIDTH, HEIGHT = 1000, 390
STEP, RADIUS = 6.1, 1.1
POINTS = re.compile(r"[ML](-?[\d.]+),(-?[\d.]+)")
ASSETS = Path(__file__).resolve().parents[1] / "dist" / "assets"
SVG = ASSETS / "world-globe.svg"
SVG_NS = "{http://www.w3.org/2000/svg}"


def outline_edges(outline):
    for ring in outline.split("Z"):
        points = [(float(x), float(y)) for x, y in POINTS.findall(ring)]
        yield from zip(points, points[1:] + points[:1])


def edge_disk_correction(edge, cx, cy):
    """Replace the circular sector with a triangle where the edge enters the disk."""
    (x0, y0), (x1, y1) = edge
    ax, ay = x0 - cx, y0 - cy
    dx, dy = x1 - x0, y1 - y0
    length_sq = dx * dx + dy * dy
    if not length_sq:
        return 0
    distance_sq = (ax * dy - ay * dx) ** 2 / length_sq
    if distance_sq >= RADIUS**2:
        return 0
    nearest = -(ax * dx + ay * dy) / length_sq
    span = sqrt((RADIUS**2 - distance_sq) / length_sq)
    start, end = max(0, nearest - span), min(1, nearest + span)
    if start >= end:
        return 0
    px, py = ax + start * dx, ay + start * dy
    qx, qy = ax + end * dx, ay + end * dy
    cross = px * qy - py * qx
    angle = atan2(cross, px * qx + py * qy)
    return (cross - RADIUS**2 * angle) / 2


def retained_rows(outline):
    edges = list(outline_edges(outline))
    disk_area = pi * RADIUS**2
    for row in range(ceil(HEIGHT / STEP)):
        # Nudge the area calculation off exact edges while preserving the grid centers.
        y = (row + .5) * STEP + 3e-8
        nearby = [edge for edge in edges if min(edge[0][1], edge[1][1]) <= y + RADIUS
                  and max(edge[0][1], edge[1][1]) >= y - RADIUS]
        crossings = sorted(x0 + (y - y0) * (x1 - x0) / (y1 - y0)
                           for (x0, y0), (x1, y1) in nearby if (y0 > y) != (y1 > y))
        retained = []
        for col in range(ceil(WIDTH / STEP)):
            x = (col + .5) * STEP + 1e-8
            area = disk_area if bisect_right(crossings, x) % 2 else 0
            area += sum(edge_disk_correction(edge, x, y) for edge in nearby
                        if min(edge[0][0], edge[1][0]) <= x + RADIUS
                        and max(edge[0][0], edge[1][0]) >= x - RADIUS)
            if area >= disk_area / 2 - 1e-7:
                retained.append(col)
        yield retained


def build():
    root = ElementTree.parse(SVG).getroot()
    stored_outline = root.find(f".//{SVG_NS}path[@id='land-outline']")
    outline = (stored_outline if stored_outline is not None else root.find(f"{SVG_NS}path")).attrib["d"]
    rows = list(retained_rows(outline))
    arcs = f"a{RADIUS},{RADIUS} 0 1,0 {2*RADIUS},0a{RADIUS},{RADIUS} 0 1,0 {-2*RADIUS},0Z"
    dots = "".join(f"M{(col+.5)*STEP-RADIUS:.2f},{(row+.5)*STEP:.2f}{arcs}"
                   for row, columns in enumerate(rows) for col in columns)
    SVG.write_text(f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {WIDTH} {HEIGHT}" preserveAspectRatio="none">
<!-- Natural Earth public-domain land outline. Whole dots generated by scripts/build_world_dots.py. -->
<defs><path id="land-outline" d="{outline}"/></defs>
<path fill="#aeb7c3" d="{dots}"/>
</svg>
''', encoding="utf-8")
    row_data = ",\n".join("    " + json.dumps(row, separators=(",", ":")) for row in rows)
    (ASSETS / "world-land-dots.js").write_text(f'''"use strict";

// Generated by scripts/build_world_dots.py from world-globe.svg.
const worldLandGrid = {{
  step:{STEP},radius:{RADIUS},
  rows:[
{row_data}
  ],
}};
''', encoding="utf-8")


if __name__ == "__main__":
    build()
